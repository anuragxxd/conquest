// Package adapter generates engine-specific configuration from WES run requests.
//
// Engines are pluggable via RunAdapter (see registry.go); workflow sources are
// not — all adapters resolve through internal/source. See issue #22.
package adapter

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	nfengine "github.com/anuragxxd/conquest/internal/engine/nextflow"
)

// NextflowRunConfig holds the parameters needed to generate Nextflow
// configuration and command-line arguments.
type NextflowRunConfig struct {
	RunID           string // WES run ID
	Runtime         nfengine.Runtime
	RepoURL         string   // normalized GitHub HTTPS URL
	Revision        string   // pinned commit SHA
	Entry           string   // optional -entry workflow name
	MainScript      string   // optional -main-script file
	Profiles        []string // optional -profile values from the workflow's nextflow.config
	WorkDirURI      string   // s3://<bucket>/v1/workflow-runs/<id>/work/nextflow/
	OutputDirURI    string   // s3://<bucket>/v1/workflow-runs/<id>/outputs/
	InternalTESBase string   // e.g. "http://conquest.services.svc.cluster.local/internal/runs/<id>"
	S3Endpoint      string   // MinIO endpoint
	S3Region        string
	WorkflowParams  json.RawMessage // raw params JSON from WES request
}

// GeneratedConfig is the output of the adapter: files to write and
// command-line args for the `nextflow run` invocation.
type GeneratedConfig struct {
	ConfigContent string   // nextflow.config file content
	ParamsContent string   // params.json file content (empty if no params)
	CLIArgs       []string // full `nextflow run ...` args
}

// GenerateNextflowConfig produces the Nextflow configuration and CLI args
// for a WES run.
//
// Key behaviors:
//   - Sets process.executor = 'tes' with nf-ga4gh plugin
//   - Sets tes.endpoint to the run-scoped internal URL (no trailing slash)
//   - Sets aws.client.endpoint + s3PathStyleAccess for MinIO compatibility
//   - Sets workDir to the run-scoped S3 work directory
//   - Includes nf-amazon plugin for S3 support
func GenerateNextflowConfig(cfg NextflowRunConfig) (*GeneratedConfig, error) {
	// nf-ga4gh appends "/v1/tasks" to tes.endpoint, so we set the base
	// to include "/ga4gh/tes" but NOT "/v1" — the plugin adds that.
	// Full path becomes: <base>/ga4gh/tes/v1/tasks
	tesEndpoint := strings.TrimSuffix(cfg.InternalTESBase, "/") + "/ga4gh/tes"
	tesEndpoint = strings.TrimSuffix(tesEndpoint, "/")

	// Nextflow expects aws.client.endpoint to include the protocol prefix.
	s3Endpoint := cfg.S3Endpoint

	var config strings.Builder
	config.WriteString("// Auto-generated by Conquest for run " + cfg.RunID + "\n")
	config.WriteString("// Do not edit.\n\n")

	// Plugins.
	if len(cfg.Runtime.PlatformPlugins) > 0 {
		config.WriteString("plugins {\n")
		for _, plugin := range cfg.Runtime.PlatformPlugins {
			config.WriteString(fmt.Sprintf("  id '%s'\n", plugin.Identifier()))
		}
		config.WriteString("}\n\n")
	}

	// TES executor.
	config.WriteString("process.executor = 'tes'\n")
	config.WriteString("process {\n")
	config.WriteString("  withName: '.*' {\n")
	config.WriteString("    storeDir = null\n")
	config.WriteString("  }\n")
	config.WriteString("}\n")
	config.WriteString(fmt.Sprintf("tes.endpoint = '%s'\n\n", tesEndpoint))

	// Work directory.
	config.WriteString(fmt.Sprintf("workDir = '%s'\n\n", cfg.WorkDirURI))

	// AWS/MinIO configuration for S3 access.
	config.WriteString("aws {\n")
	config.WriteString("  client {\n")
	config.WriteString(fmt.Sprintf("    endpoint = '%s'\n", s3Endpoint))
	config.WriteString("    s3PathStyleAccess = true\n")
	config.WriteString("  }\n")
	if cfg.S3Region != "" {
		config.WriteString(fmt.Sprintf("  region = '%s'\n", cfg.S3Region))
	}
	config.WriteString("}\n\n")

	// Disable cleanup for remote work directories (not supported).
	config.WriteString("cleanup = false\n")

	// Build CLI args.
	args := []string{
		"run",
		cfg.RepoURL,
		"-r", cfg.Revision,
		"-c", "/workspace/nextflow.config",
		"-work-dir", cfg.WorkDirURI,
	}

	if cfg.Entry != "" {
		args = append(args, "-entry", cfg.Entry)
	}
	if cfg.MainScript != "" {
		args = append(args, "-main-script", cfg.MainScript)
	}
	if len(cfg.Profiles) > 0 {
		args = append(args, "-profile", strings.Join(cfg.Profiles, ","))
	}

	// Params file.
	paramsContent := ""
	paramsJSON, err := mergeWorkflowParams(cfg.WorkflowParams, cfg.OutputDirURI)
	if err != nil {
		return nil, fmt.Errorf("merge workflow params: %w", err)
	}
	if len(paramsJSON) > 0 && string(paramsJSON) != "{}" && string(paramsJSON) != "null" {
		paramsContent = string(paramsJSON)
		args = append(args, "-params-file", "/workspace/params.json")
	}

	return &GeneratedConfig{
		ConfigContent: config.String(),
		ParamsContent: paramsContent,
		CLIArgs:       args,
	}, nil
}

func mergeWorkflowParams(raw json.RawMessage, outputDirURI string) (json.RawMessage, error) {
	params, err := normalizeWorkflowParams(raw)
	if err != nil {
		return nil, err
	}

	if outputDirURI != "" {
		if _, ok := params["outdir"]; !ok {
			params["outdir"] = outputDirURI
		}
	}

	if len(params) == 0 {
		return nil, nil
	}

	merged, err := json.Marshal(params)
	if err != nil {
		return nil, fmt.Errorf("marshal merged params: %w", err)
	}
	return merged, nil
}

func normalizeWorkflowParams(raw json.RawMessage) (map[string]any, error) {
	params := map[string]any{}
	if len(raw) == 0 || string(raw) == "null" {
		return params, nil
	}
	if err := json.Unmarshal(raw, &params); err != nil {
		return nil, fmt.Errorf("workflow_params must be a JSON object: %w", err)
	}
	return params, nil
}

// WriteConfigFiles writes the generated config and params to the workspace dir.
func WriteConfigFiles(dir string, gen *GeneratedConfig) error {
	configPath := filepath.Join(dir, "nextflow.config")
	if err := os.WriteFile(configPath, []byte(gen.ConfigContent), 0644); err != nil {
		return fmt.Errorf("write nextflow.config: %w", err)
	}

	if gen.ParamsContent != "" {
		paramsPath := filepath.Join(dir, "params.json")
		if err := os.WriteFile(paramsPath, []byte(gen.ParamsContent), 0644); err != nil {
			return fmt.Errorf("write params.json: %w", err)
		}
	}

	return nil
}
